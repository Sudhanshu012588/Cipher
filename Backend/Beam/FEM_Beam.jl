module FEMBeam

using Ferrite, FerriteGmsh, SparseArrays, LinearAlgebra

export run_beam_fem

# ── Helpers ───────────────────────────────────────────────────────────────

"""Mean coordinate (component `d`) of a facet's quadrature points."""
function facet_center(fv, facet, d::Int)
    reinit!(fv, facet)
    nq = getnquadpoints(fv)
    X = getcoordinates(facet)
    return sum(spatial_coordinate(fv, q, X)[d] for q in 1:nq) / nq
end

"""Total area of a collection of facets."""
function facets_area(dh, fv, facets)
    area = 0.0
    for facet in FacetIterator(dh, facets)
        reinit!(fv, facet)
        for q in 1:getnquadpoints(fv)
            area += getdetJdV(fv, q)
        end
    end
    return area
end

"""
Integrate a constant traction over `facets` and add it DIRECTLY into the
global load vector `f`  (vector assembly: `assemble!(f, dofs, fe)`).
"""
function add_traction!(f::Vector{Float64}, dh, fv, facets, traction::Vec{3,Float64},
                       fe::Vector{Float64})
    n_base = length(fe)
    for facet in FacetIterator(dh, facets)
        reinit!(fv, facet)
        fill!(fe, 0.0)
        for q in 1:getnquadpoints(fv)
            dΓ = getdetJdV(fv, q)
            for i in 1:n_base
                δu_i = shape_value(fv, q, i)
                fe[i] += (δu_i ⋅ traction) * dΓ
            end
        end
        assemble!(f, celldofs(facet), fe)
    end
    return f
end

"""
    run_beam_fem(msh_path, wu_kNm, Wu_kN, b1_mm; E_MPa, ν)

Solves a 3D elastostatic beam bending problem using Ferrite.jl with linear tetrahedra.
Loads the Gmsh .msh mesh generated by Mesh.jl (extrusion along X-axis).
Supports: simply supported (left pin Y+Z fixed, right roller Y fixed).
Loads: uniformly distributed load (downward Y) + mid-span point load.
Returns Dict compatible with the frontend FEM viewer schema.
"""
function run_beam_fem(
    msh_path::String,
    wu_kNm::Float64,
    Wu_kN::Float64,
    b1_mm::Float64=100.0;
    E_MPa::Float64=200e3,
    ν::Float64=0.3
)

    # ── 1. Load Gmsh mesh (in meters) ────────────────────────────────────
    grid = togrid(msh_path)
    E = E_MPa * 1e6   # Pa

    xs = [n.x[1] for n in grid.nodes]
    ys = [n.x[2] for n in grid.nodes]
    zs = [n.x[3] for n in grid.nodes]
    x_min, x_max = extrema(xs)
    y_min, y_max = extrema(ys)
    z_min, z_max = extrema(zs)

    L_beam = max(x_max - x_min, 1e-6)   # span (m) along X
    D_sec  = max(y_max - y_min, 1e-6)   # depth (m)
    B_sec  = max(z_max - z_min, 1e-6)   # width (m)

    x_mid = 0.5 * (x_min + x_max)       # mid-span X
    y_mid = 0.5 * (y_min + y_max)       # depth center Y
    z_mid = 0.5 * (z_min + z_max)       # width center Z

    @info "Beam bbox: L=$(L_beam) m, D=$(D_sec) m, B=$(B_sec) m"

    # ── 2. Interpolation & quadrature ───────────────────────────────────
    ip = Lagrange{RefTetrahedron, 1}()^3
    qr = QuadratureRule{RefTetrahedron}(2)
    qr_face = FacetQuadratureRule{RefTetrahedron}(2)
    cv = CellValues(qr, ip)
    fv = FacetValues(qr_face, ip)

    dh = DofHandler(grid)
    add!(dh, :u, ip)
    close!(dh)

    # ── 3. Boundary Conditions (using named Physical Groups from mesh) ───
    ch = ConstraintHandler(dh)

    left_set  = getfacetset(grid, "bottom_face")   # face at X=0 (left support end)
    right_set = getfacetset(grid, "top_face")      # face at X=L (right support end)

    if isempty(left_set) || isempty(right_set)
        error(
            "Beam mesh must have named Physical Groups 'bottom_face' and 'top_face'. " *
            "Regenerate the beam mesh with Mesh.jl."
        )
    end

    # Left pin: fix X (1) + Y (2) + Z (3) to prevent rigid-body X drift
    add!(ch, Dirichlet(:u, left_set, (x, t) -> [0.0, 0.0, 0.0], [1, 2, 3]))

    # Right roller: fix only Y (2) + Z (3) → allows axial slip in X + bending rotation
    add!(ch, Dirichlet(:u, right_set, (x, t) -> [0.0, 0.0], [2, 3]))

    close!(ch)

    # ── 4. Material Stiffness Tensor (isotropic steel, Pa) ───────────────
    λ = (E * ν) / ((1 + ν) * (1 - 2ν))
    μ = E / (2 * (1 + ν))
    δ(i, j) = i == j ? 1.0 : 0.0
    C = SymmetricTensor{4, 3}((i, j, k, l) -> λ * δ(i,j) * δ(k,l) + μ * (δ(i,k) * δ(j,l) + δ(i,l) * δ(j,k)))

    # ── 5. Compute cross-section properties from left end face ───────────
    left_area_m2 = 0.0
    I_strong_m4  = 0.0   # bending about Z-axis (strong axis, σ = M*y/I)

    for facet in FacetIterator(dh, left_set)
        reinit!(fv, facet)
        X = getcoordinates(facet)
        for q in 1:getnquadpoints(fv)
            dΓ = getdetJdV(fv, q)
            x_q = spatial_coordinate(fv, q, X)
            left_area_m2 += dΓ
            I_strong_m4  += ((x_q[2] - y_mid)^2) * dΓ   # ∫(y - y_mid)² dA
        end
    end

    @info "Beam section: A=$(left_area_m2) m², I_strong=$(I_strong_m4) m^4"

    # ── 6. Assemble global stiffness K across ALL elements ───────────────
    K = allocate_matrix(dh)
    f = zeros(ndofs(dh))
    assembler = start_assemble(K)          # matrix assembler ONLY (Ke)
    n_base = getnbasefunctions(cv)
    Ke = zeros(n_base, n_base)
    fe = zeros(n_base)

    for cell in CellIterator(dh)
        reinit!(cv, cell)
        fill!(Ke, 0.0)
        for q in 1:getnquadpoints(cv)
            dΩ = getdetJdV(cv, q)
            for i in 1:n_base
                δε_i = shape_symmetric_gradient(cv, q, i)
                for j in 1:n_base
                    δε_j = shape_symmetric_gradient(cv, q, j)
                    Ke[i, j] += (δε_i ⊡ C ⊡ δε_j) * dΩ
                end
            end
        end
        assemble!(assembler, celldofs(cell), Ke)
    end

    # Convert loads to SI units
    w_Nm = wu_kNm * 1000.0      # UDL in N/m (downward, -Y direction)
    P_N  = Wu_kN * 1000.0       # Point load at mid-span in N

    # ── 7. Find exterior boundary facets (faces belonging to only 1 tet) ─
    facet_counts = Dict{NTuple{3, Int}, Int}()
    for cell in grid.cells
        for f_nodes in Ferrite.facets(cell)
            key = Tuple(sort(collect(f_nodes)))
            facet_counts[key] = get(facet_counts, key, 0) + 1
        end
    end

    boundary_facets = FacetIndex[]
    for (cell_id, cell) in enumerate(grid.cells)
        for (facet_id, f_nodes) in enumerate(Ferrite.facets(cell))
            key = Tuple(sort(collect(f_nodes)))
            if facet_counts[key] == 1
                push!(boundary_facets, FacetIndex(cell_id, facet_id))
            end
        end
    end

    # Top-face facets (y ≈ y_max)
    top_facets = FacetIndex[]
    for (idx, facet) in enumerate(FacetIterator(dh, boundary_facets))
        center_y = facet_center(fv, facet, 2)
        if abs(center_y - y_max) < D_sec * 0.02
            push!(top_facets, boundary_facets[idx])
        end
    end
    top_area = facets_area(dh, fv, top_facets)

    # ── 7a. Distributed load as traction on top face ─────────────────────
    if w_Nm > 0.0 && top_area > 0.0
        q_pa = (w_Nm * L_beam) / top_area   # N/m² uniform downward pressure
        traction = Vec((0.0, -q_pa, 0.0))
        add_traction!(f, dh, fv, top_facets, traction, fe)
    end

    # ── 8. Downward mid-span point load over bearing patch ───────────────
    if P_N > 0.0 && top_area > 0.0
        bearing_half = max(0.5 * (b1_mm / 1000.0), L_beam * 0.01)
        patch_facets = FacetIndex[]

        for (idx, facet) in enumerate(FacetIterator(dh, top_facets))
            if abs(facet_center(fv, facet, 1) - x_mid) <= bearing_half
                push!(patch_facets, top_facets[idx])
            end
        end

        # Fallback to nearest top facet if mesh element size exceeds bearing_half
        if isempty(patch_facets) && !isempty(top_facets)
            best_f  = first(top_facets)
            best_dx = Inf
            for (idx, facet) in enumerate(FacetIterator(dh, top_facets))
                dx = abs(facet_center(fv, facet, 1) - x_mid)
                if dx < best_dx
                    best_dx = dx
                    best_f  = top_facets[idx]
                end
            end
            push!(patch_facets, best_f)
        end

        patch_area = facets_area(dh, fv, patch_facets)

        if patch_area > 0.0
            p_traction = Vec((0.0, -P_N / patch_area, 0.0))  # downward (-Y) N/m²
            add_traction!(f, dh, fv, patch_facets, p_traction, fe)
        end
    end

    # ── 9. Solve linear system ──────────────────────────────────────────
    apply!(K, f, ch)
    u = K \ f

    # ── 10. Post-process: nodal displacements, von Mises stress, colors ──
    n_cells = getncells(grid)
    n_nodes = getnnodes(grid)

    node_disp = Dict{Int, Vec{3, Float64}}()
    for cell in CellIterator(dh)
        dofs = celldofs(cell)
        for (local_i, nid) in enumerate(cell.nodes)
            base = 3 * (local_i - 1)
            if !haskey(node_disp, nid)
                node_disp[nid] = Vec((u[dofs[base+1]], u[dofs[base+2]], u[dofs[base+3]]))
            end
        end
    end

    max_deflection_mm = maximum(norm(d) for d in values(node_disp)) * 1000.0
    max_downward_mm   = maximum(abs(d[2]) for d in values(node_disp)) * 1000.0
    max_lateral_mm    = maximum(hypot(d[1], d[3]) for d in values(node_disp)) * 1000.0

    # Element-wise von Mises stress → nodal averaging
    von_mises_MPa = zeros(n_cells)
    node_stress_sum = zeros(n_nodes)
    node_stress_count = zeros(Int, n_nodes)

    for (idx, cell) in enumerate(CellIterator(dh))
        reinit!(cv, cell)
        u_el = u[celldofs(cell)]
        ε = function_symmetric_gradient(cv, 1, u_el)
        σ = C ⊡ ε
        s_dev = dev(σ)
        vm = sqrt(1.5 * (s_dev ⊡ s_dev)) / 1e6   # convert to MPa
        von_mises_MPa[idx] = vm

        for nid in cell.nodes
            node_stress_sum[nid] += vm
            node_stress_count[nid] += 1
        end
    end

    nodal_vm = [node_stress_count[i] > 0 ? node_stress_sum[i] / node_stress_count[i] : 0.0 for i in 1:n_nodes]
    min_vm, max_vm = extrema(nodal_vm)
    span_vm = max(max_vm - min_vm, 1e-6)

    # Flexural stress estimate (Euler-Bernoulli for simply supported beam)
    M_max_Nm = (w_Nm * L_beam^2 / 8.0) + (P_N * L_beam / 4.0)
    y_max_dist = max(abs(y_max - y_mid), D_sec * 0.5)
    flexural_MPa = M_max_Nm * y_max_dist / I_strong_m4 / 1e6

    # Stress coloring (fire colormap, same as column FEM)
    function stress_rgb(val::Float64)
        t = clamp((val - min_vm) / span_vm, 0.0, 1.0)
        r = clamp(1.5 - abs(4.0*t - 3.0), 0.0, 1.0)
        g = clamp(1.5 - abs(4.0*t - 2.0), 0.0, 1.0)
        b = clamp(1.5 - abs(4.0*t - 1.0), 0.0, 1.0)
        return (r, g, b)
    end

    # Build deformed mesh face arrays for Three.js rendering
    positions     = Float32[]
    displacements = Float32[]
    colors        = Float32[]

    tet_faces = ((1, 3, 2), (1, 2, 4), (2, 3, 4), (1, 4, 3))

    # Deduplicate shared faces
    face_counts = Dict{NTuple{3, Int}, Int}()
    for cell in grid.cells
        for f_idx in tet_faces
            tri = (cell.nodes[f_idx[1]], cell.nodes[f_idx[2]], cell.nodes[f_idx[3]])
            key = Tuple(sort(collect(tri)))
            face_counts[key] = get(face_counts, key, 0) + 1
        end
    end

    for cell in grid.cells
        for f_idx in tet_faces
            tri = (cell.nodes[f_idx[1]], cell.nodes[f_idx[2]], cell.nodes[f_idx[3]])
            key = Tuple(sort(collect(tri)))
            if get(face_counts, key, 0) == 1
                for nid in tri
                    coord = grid.nodes[nid].x
                    disp  = get(node_disp, nid, Vec((0.0, 0.0, 0.0)))
                    push!(positions, Float32(coord[1]), Float32(coord[2]), Float32(coord[3]))
                    push!(displacements, Float32(disp[1]), Float32(disp[2]), Float32(disp[3]))
                    r, g, b = stress_rgb(nodal_vm[nid])
                    push!(colors, Float32(r), Float32(g), Float32(b))
                end
            end
        end
    end

    return Dict(
        "max_deflection_mm"           => round(max_deflection_mm, digits=4),
        "max_downward_deflection"     => round(max_downward_mm, digits=4),
        "max_lateral_deflection"      => round(max_lateral_mm, digits=4),
        "nominal_flexural_MPa"        => round(flexural_MPa, digits=2),
        "min_von_mises_MPa"           => round(min_vm, digits=2),
        "max_von_mises_MPa"           => round(max_vm, digits=2),
        "avg_von_mises_MPa"           => round(sum(von_mises_MPa) / length(von_mises_MPa), digits=2),
        "yield_ratio"                 => round(max_vm / 250.0, digits=3),
        "boundary_condition_label"    => "Simply Supported (Pinned-Pinned)",
        "mesh_nodes"                  => n_nodes,
        "mesh_elements"               => n_cells,
        "positions"                   => positions,
        "displacements"               => displacements,
        "colors"                      => colors,
        "applied_load_udl_kNm"        => wu_kNm,
        "applied_point_load_kN"       => Wu_kN,
    )
end

end  # module FEMBeam